import { chromium } from "@playwright/test";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
p.on("pageerror", (e) => errors.push(e.message));
await p.addInitScript(() => localStorage.setItem("azylo-email-popup-seen", "1"));
await p.goto("http://localhost:3000/collections/convertible-sofa-beds");
await p.waitForTimeout(2500);
await p.locator('a[href*="colour=white"]').first().scrollIntoViewIfNeeded();
await p.waitForTimeout(1200);
await p.screenshot({ path: process.argv[2] + "/cards-390b.png" });
console.log(errors.length ? errors.join("\n") : "no page errors");
await b.close();
